"use strict";
const assert=require("node:assert/strict");
const Profile=require("../learning-profile");
const curriculum={tracks:[{stages:[{lessons:[{id:"a",type:"reading"},{id:"b",type:"reading"},{id:"q",type:"quiz"}]}]}]};
const map=new Map();const storage={getItem:k=>map.get(k)||null,setItem:(k,v)=>map.set(k,v)};
const create=()=>Profile.createStore(storage,curriculum);
let a=create(),b=create(),sa=a.read(),sb=b.read();
sa.done.a=true;sa=a.write(sa);sb.done.b=true;sb=b.write(sb);
assert.deepEqual(create().read().done,{a:true,b:true},"Tabs retain each other's completed lessons");
sb.done.q=true;sb.perfect.q=true;b.write(sb);
assert.deepEqual(create().read().perfect,{q:true});
sa=a.write(sa);assert.deepEqual(sa.perfect,{q:true},"A stale tab cannot remove a perfect mark");
const reset={...sa,done:{},perfect:{},lastLesson:null};const replaced=a.replace(reset);
assert.notEqual(replaced.generation,sa.generation);
sb.done.a=true;const stale=b.write(sb);assert.deepEqual(stale.done,{},"Reset generation is not undone by a stale tab");
assert.deepEqual(create().read().done,{});
const backup=JSON.stringify({...replaced,done:{b:true},avatar:"🐢",color:"mint"});
const imported=a.replace(a.importText(backup));assert.equal(imported.avatar,"🐢");assert.equal(imported.done.b,true);
assert.throws(()=>a.importText(JSON.stringify({...imported,version:77})),/Profilversion/);
assert.throws(()=>a.importText(JSON.stringify({...imported,done:{unknown:true}})),/Lernangebot/);
assert.throws(()=>a.importText(JSON.stringify({...imported,extra:"unexpected"})),/unbekannte/);
assert.throws(()=>a.importText(JSON.stringify({...imported,perfect:{q:true},done:{}})),/Quiz/);
assert.throws(()=>a.importText("x".repeat(262145)),/groß/);
const bad="{damaged-profile";map.set(Profile.KEY,bad);a=create();sa=a.read();a.write(sa);
assert([...map].some(([k,v])=>k.includes(":recovery:")&&v===bad),"Rejected raw bytes preserved exactly");
map.clear();const legacy={name:"Gast",avatar:"🧑‍💻",done:{a:true,removed:true},perfect:{},theme:"light",lastLesson:"a",dv:5};
map.set("lernstudio_v1",JSON.stringify(legacy));sa=create().read();assert.equal(sa.done.a,true);assert.equal(sa.done.removed,undefined);assert.equal(map.get("lernstudio_v1"),JSON.stringify(legacy));
const unavailable=Profile.createStore({getItem(){throw Error("denied")},setItem(){throw Error("denied")}},curriculum);
sa=unavailable.read();sa.done.a=true;sa=unavailable.write(sa);assert.equal(sa.done.a,true);assert.equal(unavailable.canPersist(),false);
console.log("Lernprofil: Migration, Wiederherstellung, Mehrtab-Fortschritt, Generationen, Importvalidierung und blockierter Speicher bestanden.");
